// Regenerates app/data/mf35-diagrams.js: original exploded line diagrams drawn from the 3D model.
// Needs Playwright with Chromium (not a runtime dependency; the output is committed).
//   node scripts/build-diagrams.mjs [--only engine,clutch] [--png outdir]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1].split(',') : null;
const pngDir = args.includes('--png') ? args[args.indexOf('--png') + 1] : null;

// View direction (scene -> camera), in model axes: x forward, y up, z right.
const FRONT = [1, 0.8, 1.15], REAR = [-1, 0.8, 1.15], SIDE = [0.35, 0.7, 1.3];
const DIAGRAMS = [
  ['engine', 'Complete engine', SIDE], ['cylinder-head-assy', 'Cylinder head', FRONT], ['engine-block-assy', 'Cylinder block', FRONT],
  ['crank-assy', 'Crankshaft, pistons and rods', SIDE], ['timing-assy', 'Camshaft and timing chain', FRONT], ['fuel-injection', 'Fuel injection', SIDE],
  ['cooling', 'Cooling system', FRONT], ['clutch', 'Clutch', REAR], ['transmission', 'Gearbox', SIDE], ['differential', 'Differential', REAR],
  ['rear-axle', 'Rear axle', REAR], ['lift-cover', 'Hydraulic lift', REAR], ['hyd-pump', 'Hydraulic pump', REAR], ['pto', 'PTO', REAR],
  ['front-axle', 'Front axle and steering', FRONT], ['brakes', 'Braking system', REAR], ['linkage', 'Three-point linkage', REAR]
];

const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
page.on('pageerror', (e) => console.error('page error:', e));
await page.goto('file://' + join(root, 'app/index.html') + '#/anatomy', { waitUntil: 'load' });
await page.waitForFunction(() => window.MF35Explorer && window.MF35Explorer.viewer(), null, { timeout: 60000 });
await page.addScriptTag({ path: join(root, 'scripts/diagram-gen.js') });

const out = { generated: new Date().toISOString().slice(0, 10), note: 'Original exploded line diagrams generated from the procedural 3D model by scripts/build-diagrams.mjs. Numbering matches the 3D exploded view of the same assembly.', diagrams: {} };
const existing = (() => { try { const s = readFileSync(join(root, 'app/data/mf35-diagrams.js'), 'utf8'); return JSON.parse(s.slice(s.indexOf('=') + 1).replace(/;\s*$/, '')).diagrams; } catch { return {}; } })();
for (const [id, title, view] of DIAGRAMS) {
  if (only && !only.includes(id)) { if (existing[id]) out.diagrams[id] = existing[id]; continue; }
  const t0 = Date.now();
  const r = await page.evaluate(([scope, view]) => {
    const viewer = window.MF35Explorer.viewer();
    const refs = (d) => viewer.explodeRefs(scope, d).length;
    const depth = refs('all') <= 40 ? 'all' : (refs(2) <= 40 ? 2 : 1);
    return window.MF35DiagramGen.gen(viewer, { scope, depth, view });
  }, [id, view]);
  r.title = title;
  out.diagrams[id] = r;
  console.log(`${id.padEnd(20)} depth=${String(r.depth).padEnd(3)} items=${String(r.items.length).padEnd(3)} meshes=${String(r.meshes).padEnd(4)} loops=${String(r.loops).padEnd(5)} svg=${(r.svg.length / 1024).toFixed(0)} KB  ${Date.now() - t0} ms`);
  if (pngDir) {
    mkdirSync(pngDir, { recursive: true });
    const html = `<!doctype html><meta charset="utf-8"><style>body{margin:0;background:#fff}svg{width:1400px;display:block}.parts path{stroke:#2b3038;stroke-width:1.1;stroke-linejoin:round}.parts path.c{fill:none;stroke-width:.8;stroke:#4a515b}.parts .ghost path{stroke:#9aa3ad;stroke-dasharray:6 4}.dg-callouts line{stroke:#1f4e9c;stroke-width:1.2}.dg-callouts .tip{fill:#1f4e9c}.dg-callouts .num{fill:#fff;stroke:#1f4e9c;stroke-width:2}.dg-callouts text{font:600 20px system-ui,sans-serif;fill:#1f4e9c}</style>${r.svg}`;
    const p2 = await browser.newPage({ viewport: { width: 1400, height: 100 }, deviceScaleFactor: 1 });
    await p2.setContent(html);
    await p2.locator('svg').screenshot({ path: join(pngDir, id + '.png') });
    await p2.close();
  }
}
await browser.close();
const ordered = {}; for (const [id] of DIAGRAMS) if (out.diagrams[id]) ordered[id] = out.diagrams[id];
out.diagrams = ordered;
writeFileSync(join(root, 'app/data/mf35-diagrams.js'), '// Generated by scripts/build-diagrams.mjs. Do not edit by hand.\nwindow.MF35_DIAGRAMS = ' + JSON.stringify(out) + ';\n');
const total = Object.values(out.diagrams).reduce((s, d) => s + d.svg.length, 0);
console.log(`wrote app/data/mf35-diagrams.js: ${Object.keys(out.diagrams).length} diagrams, ${(total / 1024).toFixed(0)} KB of SVG`);
