#!/usr/bin/env node
// Bundles data/*.json into app/data/mf35-data.js so the app works when
// index.html is opened straight from disk (file:// blocks fetch() of JSON).
// Usage: node scripts/build-data.mjs   (run after any data edit; validate first)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'data', f), 'utf8'));
const bundle = {
  generatedAt: new Date().toISOString(),
  sources: read('sources.json').sources,
  configurations: read('configurations.json'),
  hierarchy: read('hierarchy.json').root,
  technical: read('technical.json'),
  suppliers: read('suppliers.json')
};
mkdirSync(join(root, 'app', 'data'), { recursive: true });
const out = join(root, 'app', 'data', 'mf35-data.js');
writeFileSync(out,
  '/* GENERATED by scripts/build-data.mjs from data/*.json. Do not edit by hand. */\n' +
  'window.MF35_DATA = ' + JSON.stringify(bundle) + ';\n');
console.log('Wrote', out);
